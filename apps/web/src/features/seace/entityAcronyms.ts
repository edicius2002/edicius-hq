const normalize = (value: string) =>
  value
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, ' ')
    .trim();

const acronymByName = new Map(
  [...uniqueEntityNames, ...aliases].map(([name, acronym]) => [normalize(name), acronym]),
);

export const uniqueEntityAcronym = (entity: string, region: string): string | null => {
  if (normalize(region) !== 'AREQUIPA') return null;
  return acronymByName.get(normalize(entity)) ?? null;
};
