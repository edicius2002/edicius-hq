import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/*
 * The airport search catalog, generated from the same checked-in OurAirports
 * extract the retired FastAPI search read (`services/api/app/data/airports.tsv`,
 * public domain): 4,162 airports with an IATA code and scheduled service.
 *
 * The Supabase search that replaced FastAPI in #203 looked only at
 * `fare_airports` — the dozen airports the archive had already collected — so
 * typing `JFK`, `BOG` or `CDG` offered nothing. This puts the full list back.
 *
 * `city_key` and `name_key` are folded here, once, the way the old search did:
 * lower case with accents removed, so "cusco" finds Cusco and "malaga" Málaga.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'services/api/app/data/airports.tsv');
const destination = resolve(root, 'supabase/migrations/20260925000000_airport_catalog_search.sql');

const fold = (text) => text.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase();
const literal = (text) => `'${text.replace(/'/g, "''")}'`;

const rows = readFileSync(source, 'utf8').trimEnd().split(/\r?\n/);
const seen = new Set();
const values = rows.map((row, index) => {
  const parts = row.split('\t');
  if (parts.length !== 4) throw new Error(`Invalid airport row ${index + 1}.`);
  const [code, city, country, name] = parts.map((part) => part.trim());
  // 67 remote strips have no municipality in the source; the name still finds them.
  if (!/^[A-Z0-9]{3}$/.test(code) || seen.has(code) || !name)
    throw new Error(`Invalid airport row ${index + 1}.`);
  seen.add(code);
  return `  (${[code, name, city, country, fold(city), fold(name)].map(literal).join(',')})`;
});
if (values.length !== 4162) throw new Error(`Expected 4162 airports, found ${values.length}.`);

const migration = `-- Generated by scripts/generate-airport-catalog-migration.mjs from the
-- checked-in OurAirports extract (CC0/public domain). Do not hand-edit.
--
-- The airport search looked only at fare_airports, the airports the archive had
-- already collected, so a code nobody had watched offered nothing. This installs
-- the full searchable catalog and ranks it the way the retired FastAPI search
-- did: exact code, code prefix, city prefix, city, airport name, country.
create table if not exists public.airport_catalog (
  code text primary key check (code ~ '^[A-Z0-9]{3}$'),
  name text not null,
  city text not null,
  country text not null,
  city_key text not null,
  name_key text not null
);

insert into public.airport_catalog(code,name,city,country,city_key,name_key) values
${values.join(',\n')}
on conflict (code) do update set
  name = excluded.name,
  city = excluded.city,
  country = excluded.country,
  city_key = excluded.city_key,
  name_key = excluded.name_key;

alter table public.airport_catalog enable row level security;
revoke all on table public.airport_catalog from public, anon, authenticated, service_role;

create or replace function public.search_owner_airports(p_query text, p_limit integer)
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  -- The same fold the catalog keys were built with, for the accents a keyboard
  -- is likely to produce; codes are ASCII already.
  v_needle text := lower(translate(
    trim(coalesce(p_query, '')),
    'ÁÀÂÄÃÅáàâäãåÉÈÊËéèêëÍÌÎÏíìîïÓÒÔÖÕóòôöõÚÙÛÜúùûüÑñÇç',
    'AAAAAAaaaaaaEEEEeeeeIIIIiiiiOOOOOoooooUUUUuuuuNnCc'
  ));
begin
  if auth.uid() is null or not exists (
    select 1 from public.edicius_owners where owner_id = auth.uid()
  ) then
    raise exception using errcode = '42501', message = 'not_edicius_owner';
  end if;
  if p_limit < 1 or p_limit > 25 then
    raise exception using errcode = '22023', message = 'invalid_airport_search_limit';
  end if;
  return jsonb_build_object(
    'query', p_query,
    'matches', coalesce((
      select jsonb_agg(jsonb_build_object('code', code, 'name', name, 'city', city, 'country', country)
                       order by rank, code)
      from (
      select code, name, city, country, rank
      from (
        select code, name, city, country,
               case
                 when lower(code) = v_needle then 0
                 when left(lower(code), length(v_needle)) = v_needle then 1
                 when left(city_key, length(v_needle)) = v_needle then 2
                 when position(v_needle in city_key) > 0 then 3
                 when position(v_needle in name_key) > 0 then 4
                 when position(v_needle in lower(country)) > 0 then 5
               end as rank
          from (
            select code, name, city, country, city_key, name_key
              from public.airport_catalog
            union all
            -- An archived airport the catalog lacks is still findable, as before.
            select a.code, coalesce(a.name, a.code), coalesce(a.city, ''), coalesce(a.country, ''),
                   lower(coalesce(a.city, '')), lower(coalesce(a.name, ''))
              from public.fare_airports a
             where not exists (select 1 from public.airport_catalog c where c.code = a.code)
          ) airports
         where v_needle <> ''
      ) ranked
      where rank is not null
      order by rank, code
      limit p_limit
      ) best
    ), '[]'::jsonb)
  );
end;
$$;
`;
writeFileSync(destination, migration, 'utf8');
