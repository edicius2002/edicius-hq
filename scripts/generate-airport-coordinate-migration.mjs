import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'services/api/app/data/airport_coordinates.tsv');
const destination = resolve(
  root,
  'supabase/migrations/20260919020000_airport_coordinate_reference.sql',
);
const rows = readFileSync(source, 'utf8').trimEnd().split(/\r?\n/);
if (rows.shift() !== 'iata\tlatitude\tlongitude') throw new Error('Unexpected coordinate header.');

const seen = new Set();
const numeric = /^-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$/;
const values = rows.map((row, index) => {
  const [code, latitudeText, longitudeText, ...extra] = row.split('\t');
  const latitude = Number(latitudeText);
  const longitude = Number(longitudeText);
  if (
    extra.length ||
    !/^[A-Z0-9]{3}$/.test(code) ||
    seen.has(code) ||
    !numeric.test(latitudeText) ||
    !numeric.test(longitudeText) ||
    !Number.isFinite(latitude) ||
    !Number.isFinite(longitude) ||
    latitude < -90 ||
    latitude > 90 ||
    longitude < -180 ||
    longitude > 180
  )
    throw new Error(`Invalid coordinate row ${index + 2}.`);
  seen.add(code);
  return `  ('${code}',${latitudeText},${longitudeText})`;
});
if (values.length !== 9054) throw new Error(`Expected 9054 coordinates, found ${values.length}.`);

const migration = `-- Generated by scripts/generate-airport-coordinate-migration.mjs from the
-- checked-in reduced OurAirports dataset (CC0/public domain). Do not hand-edit.
create table if not exists public.airport_coordinate_reference (
  code text primary key check (code ~ '^[A-Z0-9]{3}$'),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180)
);

insert into public.airport_coordinate_reference(code,latitude,longitude) values
${values.join(',\n')}
on conflict (code) do update set
  latitude = excluded.latitude,
  longitude = excluded.longitude;

alter table public.airport_coordinate_reference enable row level security;
revoke all on table public.airport_coordinate_reference
  from public, anon, authenticated, service_role;
`;
writeFileSync(destination, migration, 'utf8');
